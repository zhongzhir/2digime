function item(
  n: number,
  title: string,
  text: string,
  extra?: { url?: string; expiresAt?: string },
): NetworkItem {
  const id = `ni_${String(n).padStart(2, '0')}`;
  return {
    schemaVersion: 1,
    itemId: id,
    publisherSubjectId: PUBLISHER,
    publisherDisplayName: '公开候选试验源',
    kind: 'content',
    createdAt: `2026-09-08T04:${String(n).padStart(2, '0')}:00.000Z`,
    visibility: 'public',
    content: {
      title,
      text,
      ...(extra?.url ? { url: extra.url } : {}),
    },
    provenance: {
      origin: 'seed',
      actor: 'owner',
      statedAt: NOW,
    },
    ...(extra?.expiresAt ? { expiresAt: extra.expiresAt } : {}),
  };
}

